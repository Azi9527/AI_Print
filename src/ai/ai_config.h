// ★★★ 回声抵消（AEC）—— 打断播报的**治本方案** ★ 2026-10-04 晚 第四版
//   老陈给的硬件事实（决定性）：**ES8311 的音频输出既接功放，又直接接到 ES7210 的 MIC3**。
//   ⇒ 我们播出来的声音，是**电**回麦克风的，不是空气回声：几乎无混响、无延迟抖动。
//   而 I2S 是全双工、收发共用同一组 MCLK/BCK/WS —— **我们正在写出去的 PCM 就是最准的参考**，
//   不需要去读 MIC3、也不需要任何额外硬件。
//
//   模型：mic[n] ≈ Σ w[k]·tx[n-D-k]      （D = codec 群延迟，固定且很小）
//   用 NLMS 自适应滤波把这条电回声从麦克风里减掉，**残差就是纯人声** →
//   打断判定再也不用在"自激"和"打不断"之间走钢丝（前几版的死结就在这：
//   回声电平 ≈ 人声电平，纯靠能量猜永远猜不准）。
//
//   为什么抽头只要 128：路径短、展宽小，128 抽头(8ms) 足够，CPU ≈ 4M MAC/s（可忽略）。
//
// ★★★ 改版30 的重大修正（老陈提议 + 数据手册核实）★★★
//   老陈问："ES7210 MIC3 做硬件回采参考会不会好？" —— **方向完全正确**，但有个硬约束：
//   ① ES7210 在普通 I2S 两声道模式下，SDOUT1 **固定**是 左=ADC1(MIC1)、右=ADC2(MIC2)，
//      **没有"把 MIC3 挪到右槽"的寄存器**（手册 REG0x12 bit[1:0] 只有：00=ADC12→SDOUT1
//      & ADC34→SDOUT2 / 01=DSP-TDM / 10=I2S-TDM / 11=多设备TDM）。
//   ② 想让 MIC3 出来只能开 TDM 4 时隙 ⇒ BCLK 变 4 倍 ⇒ **ES8311 播放会一起废掉**
//      （这块板 ES8311/ES7210 共用同一组 MCLK/BCLK/WS）。
//   ⇒ 唯一低成本正解：**把"ES8311 输出 → ES7210"的那根回采线从 MIC3 改接到 MIC2**。
//      这样 MIC1 仍是麦克风、MIC2 就是参考，**零 I2S 改动**。
//
//   硬件回采为什么比"TX PCM 参考"强得多（这是 AEC 一直不收敛的根因）：
//     · TX PCM 参考的时间戳是"**写进 I2S DMA 那一刻**"，而它实际播出要再等 DMA 里
//       积压的时长；DMA 填充量随网络抖动忽多忽少 ⇒ 参考↔回声的延迟 D **本身在漂**
//       （改版29 实测：D 在 95~2659 之间乱跳）⇒ NLMS 永远对不齐。
//     · MIC2 参考是**同一个 ES7210 在同一帧里采的** ⇒ 与麦克风天然同步，
//       D ≡ 0（只剩喇叭→空气→麦克风那 1~3ms，128 抽头罩得住）⇒ **不需要任何延迟搜索**。
#define AEC_ENABLE       1      // 0 = 关掉 AEC（退回纯能量法＝上几版的状态）

// ★★★ I2S 通道模式（2026-10-12，老陈选"软件改 TDM 读 MIC3 回采"）★★★
