// ★★ AEC 参考来源（改版30）★★ 切换点：把回采线挪到 MIC2 后改成 1
//   0 = TX PCM（软件参考，靠相关搜索对齐延迟 D）—— 现状，不需要动硬件
//   1 = MIC2 硬件回采（右声道 = ES8311 输出）—— ★推荐，需要把回采线从 MIC3 挪到 MIC2
//       切成 1 后：ADC2 会被打开、右声道当参考、D 固定为 0、**完全跳过延迟搜索**。
