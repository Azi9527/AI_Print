// ============================================================
// 构造函数
// ============================================================
TFTDisplay::TFTDisplay() : _spi(nullptr), _frameBuf(nullptr), _bufSize(0), _cursorX(0), _cursorY(0) {}

// ============================================================
// 主初始化
// ============================================================
// 完整初始化序列：
//   1. initSPI() —— 初始化 SPI 总线
//   2. allocBuffer() —— 分配 PSRAM 帧缓冲
//   3. initST7789() —— 发送 ST7789 初始化命令
bool TFTDisplay::begin() {
    if (!initSPI()) return false;
    if (!allocBuffer()) return false;
    initST7789();
    return true;
}

// ============================================================
// SPI 总线初始化
// ============================================================
// 【如需修改 SPI 频率】
//   _spi->setFrequency() 改其他值
//   40MHz 是 ST7789 的典型最大速度
//   更高（80MHz）可能不稳定，更低（20MHz）兼容性更好
bool TFTDisplay::initSPI() {
    _spi = new SPIClass(HSPI);
    _spi->begin(TFT_SCK, -1, TFT_MOSI, TFT_CS);
    _spi->setFrequency(40000000);  // 40MHz SPI 时钟

    pinMode(TFT_CS, OUTPUT);
    pinMode(TFT_DC, OUTPUT);
    pinMode(TFT_BL, OUTPUT);
    pinMode(TFT_RST, OUTPUT);

    digitalWrite(TFT_BL, LOW);
    return true;
}

// ============================================================
// 帧缓冲分配
// ============================================================
// 【PSRAM 分配策略】
//   优先从 PSRAM 分配（ps_malloc）
