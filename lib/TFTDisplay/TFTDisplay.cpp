/********************************************************
 * TFTDisplay.cpp - ST7789 TFT 驱动库实现
 *
 * 实现原理：
 *   1. SPI + DMA 发送像素数据（40MHz）
 *   2. PSRAM 帧缓冲——先在内存中绘制，再批量发到屏幕
 *   3. 8x16 等宽字体（内置字体表）
 *
 * 硬件接线：
 *   IO40=MOSI, IO41=SCK, IO11=CS, IO39=DC, IO42=BL, IO44=RST
 *   SPI 速度：40MHz（默认），可在 initSPI() 中修改
 *
 * 【如需修改颜色模式】
 *   ST7789 支持 RGB565 / RGB666 两种模式
 *   当前用 RGB565（0x55 = 16bit/pixel）
 *   如需 RGB666（18bit）：改 COLMOD 为 0x66，并修改像素写入为 3字节/pixel
 *
 * 【如需屏幕旋转】
 *   修改 MADCTL (0x36) 参数：
 *     0x00 = 竖屏（240x320）
 *     0x60 = 横屏（320x240, 镜像）
 *     0xC0 = 横屏（320x240, 正常）
 *     0xA0 = 横屏（320x240, 翻转）
 *   注意：旋转后需同步修改 TFT_WIDTH/TFT_HEIGHT
 ********************************************************/

