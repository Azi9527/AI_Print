// ============================================================
// RGB565 位图绘制（JPEG 解码输出用）
// ============================================================
// 【注意！】bitmap 数据必须是 RGB565 格式（主机字节序的 uint16_t 数组）。
// 字节序转换在 pushPixels() 里统一做，别在这里再换一次。
void TFTDisplay::drawRGBBitmap(int16_t x, int16_t y, const uint16_t* bitmap, int16_t w, int16_t h) {
    pushPixels(x, y, w, h, bitmap);
}

// ============================================================
// 快速像素批量写入
// 【2026-10-03 修正字节序】ST7789 16bpp 要求"高字节先发"，而 uint16_t
//   数组在 ESP32 内存里是小端（低字节在前）。原来直接把数组指针丢给
//   SPI，红蓝分量整体错位 —— 屏幕上表现就是一片彩色噪声。
//   现在逐块交换字节后再发，颜色与 drawPixel() 完全一致。
// ============================================================
void TFTDisplay::pushPixels(int16_t x, int16_t y, int16_t w, int16_t h, const uint16_t* data) {
    if (w <= 0 || h <= 0 || !data) return;
    setWindow(x, y, x + w - 1, y + h - 1);

    const uint32_t total = (uint32_t)w * h;
    const uint32_t CHUNK = 2048;                  // 每次 4KB，够快又不吃内存
    static uint8_t* sw = nullptr;
    if (!sw) sw = (uint8_t*)malloc(CHUNK * 2);
    if (!sw) {                                    // 分配失败：退化成逐像素
        for (uint32_t i = 0; i < total; i++) {
            uint8_t b[2] = {(uint8_t)(data[i] >> 8), (uint8_t)(data[i] & 0xFF)};
            tftDataBuf(b, 2);
        }
        return;
    }
    uint32_t done = 0;
    while (done < total) {
        const uint32_t n = (total - done) > CHUNK ? CHUNK : (total - done);
        for (uint32_t i = 0; i < n; i++) {
            const uint16_t v = data[done + i];
            sw[i * 2]     = (uint8_t)(v >> 8);
            sw[i * 2 + 1] = (uint8_t)(v & 0xFF);
        }
        tftDataBuf(sw, n * 2);
        done += n;
    }
}

// ============================================================
// 帧缓冲管理
// ============================================================
// 【内存使用场景】
//   下载图片前：freeBuffer() → 释放 153KB 用于下载缓冲
//   显示图片后：reallocBuffer() → 重新分配帧缓冲用于绘图
void TFTDisplay::freeBuffer() {
    if (_frameBuf) {
        free(_frameBuf);
        _frameBuf = nullptr;
        _bufSize = 0;
        Serial.println("[TFT] Frame buffer freed");
    }
}

bool TFTDisplay::reallocBuffer() {
    if (_frameBuf) return true;
    return allocBuffer();
}
