void TFTDisplay::setCursor(int16_t x, int16_t y) {
    _cursorX = x;
    _cursorY = y;
}

int16_t TFTDisplay::getCursorX() { return _cursorX; }
int16_t TFTDisplay::getCursorY() { return _cursorY; }

// 打印单个字符（8x16 等宽字体）
// 字符宽8像素，高16像素
// 【如需其他字体大小】
//   可以修改 font8x16 表或改用其他字体表
void TFTDisplay::printChar(char c, uint16_t fgColor, uint16_t bgColor) {
    if (c < ' ' || c > '~') c = ' ';
    uint8_t idx = c - ' ';

    for (int row = 0; row < 16; row++) {
        uint8_t line = pgm_read_byte(&font8x16[idx][row]);
        for (int col = 0; col < 8; col++) {
            uint16_t color = (line & 0x80) ? fgColor : bgColor;
            drawPixel(_cursorX + col, _cursorY + row, color);
            line <<= 1;
        }
    }
    _cursorX += 8;
    if (_cursorX > _W - 8) {
        _cursorX = 0;
        _cursorY += 16;
        if (_cursorY > _H - 16) _cursorY = 0;
    }
}

void TFTDisplay::print(const char* str, uint16_t fgColor, uint16_t bgColor) {
    while (*str) {
        printChar(*str++, fgColor, bgColor);
    }
}

void TFTDisplay::printInt(int val, uint16_t fgColor, uint16_t bgColor) {
    char buf[16];
    itoa(val, buf, 10);
    print(buf, fgColor, bgColor);
}

